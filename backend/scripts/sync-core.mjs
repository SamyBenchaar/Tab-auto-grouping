// Copies the classification core from extension/src/core (single source of truth) into
// backend/src/core, so that the backend folder stays self-contained for Cloud Run builds.
// Runs automatically before `npm run dev`, `npm test` and `npm run deploy`.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const GENERATED_HEADER = '// GENERATED by `npm run sync-core` from extension/src/core — do not edit here.\n';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../extension/src/core');
const target = resolve(here, '../src/core');

if (!existsSync(source)) {
  console.log('[sync-core] extension/src/core introuvable : copie existante conservée.');
  process.exit(0);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
const files = readdirSync(source).filter((file) => file.endsWith('.js'));
for (const file of files) {
  writeFileSync(join(target, file), GENERATED_HEADER + readFileSync(join(source, file), 'utf8'));
}
console.log(`[sync-core] ${files.length} fichiers copiés vers backend/src/core.`);
